class ApprovalRemoteDataSource {
  ApprovalRemoteDataSource(this._dio);

  final Dio _dio;

  Future<ApprovalDashboard> fetchDashboard() async {
    if (AppEnv.baseUrl.isEmpty) {
      return _mockDashboard();
    }

    try {
      final response = await _dio.get<Map<String, dynamic>>(
        '/approvals/dashboard',
      );
      return ApprovalDashboard.fromJson(response.data ?? <String, dynamic>{});
    } on DioException {
      return _mockDashboard();
    }
  }

  Future<ApprovalDocument> fetchDocument(String id) async {
    final dashboard = await fetchDashboard();
    return [
      ...dashboard.processingDocuments,
      ...dashboard.waitingDocuments,
    ].firstWhere(
      (document) => document.id == id,
      orElse: () => dashboard.processingDocuments.first,
    );
  }

  Future<void> approveDocument(String id) async {
    if (AppEnv.baseUrl.isEmpty) {
      return;
    }

    await _dio.post<void>('/approvals/$id/approve');
  }

